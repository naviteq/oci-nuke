// LifecycleState or TimeCreated field, per 04-RESEARCH.md Q4), so it documents only name,
// compartment_id, and namespace.
//
// This hand-maintained map only covers 5 of 37 registered types. Exact-key-set correctness for
// every OTHER registered type is proven separately, without a hand-maintained list, by
// tools/generate-docs/freshness_test.go's TestPropertyKeys_MatchCommittedDocs_AllRegisteredTypes
// -- see CONTRIBUTING.md section 6's "Properties() exact-key-set correctness" for why that shared
