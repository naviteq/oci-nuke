// Package docs_test proves tools/generate-docs' output (DOC-04), committed under docs/resources/,
// covers every registered resource type -- run for the first time against the real,
// fully-populated resources package, not the fixture-based unit tests already covering
// tools/generate-docs/main.go's extraction logic in isolation.
package docs_test

