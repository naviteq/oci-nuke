// indexMarkdownFile is docs/resources/index.md -- the generated resource-type index. It lives in
// the same directory as the per-type pages but is not one of them.
const indexMarkdownFile = "index.md"

// TestGeneratedDocsCoverage_MatchesRegisteredTypeCount is DOC-04's coverage guarantee stated as
// its own named criterion: the exact set of docs/resources/<Type>.md files present on disk must
// equal the exact set of names registry.GetNames() returns -- not merely a non-zero file count,
// and not merely a matching count that could hide a name mismatch (e.g. a stale doc left behind
// for a type that was since renamed or removed, while a genuinely new type's doc silently never
// got generated).
func TestGeneratedDocsCoverage_MatchesRegisteredTypeCount(t *testing.T) {
	entries, err := os.ReadDir(".")
	if err != nil {
		t.Fatalf("reading docs/resources/: %v", err)
	}

	gotNames := make(map[string]bool)
	for _, entry := range entries {
		name := entry.Name()
		// indexFileName is generated by the same tool but is a page, not a type -- it must not
		// be read as one.
		if entry.IsDir() || !strings.HasSuffix(name, ".md") || name == indexMarkdownFile {
			continue
		}
		gotNames[strings.TrimSuffix(name, ".md")] = true
	}

	wantNames := make(map[string]bool)
	for _, name := range registry.GetNames() {
		wantNames[name] = true
	}

	var missingDocs, staleDocs []string
	for name := range wantNames {
		if !gotNames[name] {
			missingDocs = append(missingDocs, name)
		}
	}
	for name := range gotNames {
		if !wantNames[name] {
			staleDocs = append(staleDocs, name)
		}
	}
	sort.Strings(missingDocs)
	sort.Strings(staleDocs)

	if len(missingDocs) > 0 {
		t.Errorf(
			"registered resource type(s) with no generated doc: %s -- re-run `go run "+
				"./tools/generate-docs` and commit its output under docs/resources/",
			strings.Join(missingDocs, ", "),
		)
	}
	if len(staleDocs) > 0 {
		t.Errorf(
			"docs/resources/*.md file(s) with no corresponding registered type: %s -- these are "+
				"stale (the type was renamed or removed); delete the stale .md file(s) and re-run "+
				"`go run ./tools/generate-docs`",
			strings.Join(staleDocs, ", "),
		)
	}

	if len(gotNames) != len(wantNames) {
		t.Errorf(
			"docs/resources/ contains %d .md file(s), registry.GetNames() returns %d name(s) -- "+
				"counts must match exactly (DOC-04)",
			len(gotNames), len(wantNames),
		)
	}
}

// Property key constants shared by baseProperties across nearly every spot-checked type below --
